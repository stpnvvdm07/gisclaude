def hbar(s, x, y, w, parts, h=44, size=24):
    tot = sum(v for v, _, _ in parts); xx = x
    for v, c, lab in parts:
        L = w * v / tot
        if L <= 0: continue
        s.rect(xx, y, L - 3, h, c)
        if lab and L > tw(lab, size, "Semibold") + 20: T(s, xx + 12, y + (h - size * 1.12) / 2, L - 16, lab, size, "Semibold", WH if lum(c) < 0.45 else DK)
        xx += L
def mapimg(s, key, x, y, north_at="tl", sb=True):
    m = M[key]; s.img(x, y, m["w"], m["h"], f"maps/{key}.png", tone="#F9F3E7")
    ns = 80 if m["w"] >= 1200 else 60; ny = y + (56 if y < 40 else PAD)
    north(s, x + PAD + 4 if north_at == "tl" else x + m["w"] - PAD - ns, ny, ns)
    if sb:
        step = next(v for v in (50, 100, 200, 250, 500, 1000) if v / m["mpp"] >= 100); L = step / m["mpp"]
        by = y + m["h"] - (92 if y + m["h"] > 1050 else 44); bw = 2 * L + 80
        s.rect(x + m["w"] - PAD - bw, by - 40, bw, 56, "#F9F3E7", op=0.85)
        scalebar(s, x + m["w"] - PAD - 2 * L - 40, by, m["mpp"], step=step)
    return m
def fit_legend(s, x, y, items, w, color, max_h, cols=1, sizes=(26, 24, 22, 20)):
    for sz in sizes:
        t = Slide(); h = legend(t, x, y, items, w, color, sz, cols=cols, row=sz + 12)
        if h <= max_h: return legend(s, x, y, items, w, color, sz, cols=cols, row=sz + 12)
    return legend(s, x, y, items, w, color, sizes[-1], cols=cols, row=sizes[-1] + 10)

