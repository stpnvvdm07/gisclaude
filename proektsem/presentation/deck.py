def fit_legend(s, x, y, items, w, color, max_h, cols=1, sizes=(24, 22, 20, 18)):
    """Подбирает кегль, чтобы легенда уложилась в max_h."""
    for sz in sizes:
        t = Slide(); h = legend(t, x, y, items, w, color, sz, cols=cols, row=sz + 14)
        if h <= max_h: return legend(s, x, y, items, w, color, sz, cols=cols, row=sz + 14)
    return legend(s, x, y, items, w, color, sizes[-1], cols=cols, row=sizes[-1] + 12)

