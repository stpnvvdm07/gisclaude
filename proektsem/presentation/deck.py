def mapimg(s, key, x, y, north_rot=-26.75, sb=True, north_pos=None):
    m = M[key]; e = s.img(x, y, m["w"], m["h"], f"maps/{key}.png"); e["tone"] = PP
    nx, ny = north_pos or (x + PAD, y + 72)
    north(s, nx, ny, 64 if m["w"] >= 900 else 48, rot=north_rot)
    if sb:
        step = next(v for v in (50, 100, 200, 250, 500, 1000) if v / m["mpp"] >= 96)
        L = step / m["mpp"]; sy = y + m["h"] - (80 if y + m["h"] > 1050 else 40)     # над подвалом
        scalebar(s, x + m["w"] - PAD - 2 * L - 20, sy, m["mpp"], step=step)
    return m

